"""Immutable history storage in an explicitly trusted application directory."""

from __future__ import annotations

import hashlib
import json
import os
import re
import stat
import tempfile
from collections.abc import Callable
from pathlib import Path

MAX_CONTENT_BYTES = 16 * 1024 * 1024


class HistoryCacheError(ValueError):
    """Invalid/unavailable cache; never includes stored contents or local paths."""


def _digest(value: object) -> str:
    if not isinstance(value, str) or re.fullmatch(r"[0-9a-f]{64}", value) is None:
        raise HistoryCacheError("invalid history cache reference")
    return value


def _read(path: Path, limit: int) -> bytes:
    if path.is_symlink() or not stat.S_ISREG(path.stat().st_mode):
        raise HistoryCacheError("invalid history cache file")
    with path.open("rb") as stream:
        payload = stream.read(limit + 1)
    if len(payload) > limit:
        raise HistoryCacheError("invalid history cache size")
    return payload


def _unique(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise HistoryCacheError("invalid history cache duplicate reference")
        result[key] = value
    return result


def _resolve(root: Path, key: str) -> bytes:
    reference = json.loads(_read(root / f"{key}.json", 4096), object_pairs_hook=_unique)
    if (
        not isinstance(reference, dict)
        or set(reference) != {"version", "input", "sha256"}
        or type(reference["version"]) is not int
        or reference["version"] != 1
        or reference["input"] != key
    ):
        raise HistoryCacheError("invalid history cache manifest")
    digest = _digest(reference["sha256"])
    payload = _read(root / f"{digest}.csv", MAX_CONTENT_BYTES)
    if hashlib.sha256(payload).hexdigest() != digest:
        raise HistoryCacheError("invalid history cache content hash")
    return payload


def _publish(path: Path, payload: bytes) -> None:
    """Flush a private temporary inode, then link exclusively; never replace."""
    temporary: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".history-", delete=False) as f:
            temporary = Path(f.name)
            f.write(payload)
            f.flush()
            os.fsync(f.fileno())
        try:
            os.link(temporary, path)
        except FileExistsError:
            if _read(path, max(4096, MAX_CONTENT_BYTES)) != payload:
                raise HistoryCacheError("invalid history cache publication conflict") from None
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def load_or_generate(root: Path, input_sha256: str, generate: Callable[[], bytes]) -> bytes:
    """Caller owns/trusts root; missing reference generates, invalid entries fail closed."""
    key = _digest(input_sha256)
    if not root.is_absolute():
        raise HistoryCacheError("invalid history cache directory")
    try:
        root.mkdir(mode=0o700, parents=True, exist_ok=True)
        reference = root / f"{key}.json"
        if reference.exists() or reference.is_symlink():
            return _resolve(root, key)
        payload = generate()
        if not isinstance(payload, bytes) or len(payload) > MAX_CONTENT_BYTES:
            raise HistoryCacheError("invalid history cache generated bytes")
        digest = hashlib.sha256(payload).hexdigest()
        _publish(root / f"{digest}.csv", payload)
        manifest = {"version": 1, "input": key, "sha256": digest}
        _publish(reference, json.dumps(manifest, sort_keys=True).encode("ascii"))
        return _resolve(root, key)
    except (OSError, ValueError, TypeError, UnicodeError, RecursionError):
        raise HistoryCacheError("invalid history cache; inspect trusted cache directory") from None
