import {chromium} from '@playwright/test';
import {mkdir,writeFile,copyFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const url=process.env.QOIMA_TEST_URL||'http://127.0.0.1:4180';
const directory=resolve('../work/night-video');await mkdir(directory,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--mute-audio']});
const context=await browser.newContext({viewport:{width:1366,height:768},deviceScaleFactor:1,recordVideo:{dir:directory,size:{width:1366,height:768}}});
const began=Date.now();const page=await context.newPage();const video=page.video();
await page.goto(url);await page.waitForFunction(()=>document.querySelector('main')?.dataset.phase==='ready');
await page.evaluate(()=>{const v=window.__QOIMA_VIEWER__;v.audio.setMuted(true);v.setQuality('low');v.replay.reset();v.overview();});
await page.waitForTimeout(1000);
const readyOffset=(Date.now()-began)/1000;const storyBegan=Date.now();const chapters=[];
const run=await page.evaluate(()=>window.__QOIMA_VIEWER__.replay.getRun());
const loadedBuildAssets=await page.evaluate(()=>performance.getEntriesByType('resource').map(item=>new URL(item.name).pathname).filter(path=>path.endsWith('.js')).sort());
const event=kind=>run.events.find(event=>event.kind===kind);
const scan=run.actions.find(action=>action.actor_id==='S01'&&action.operation==='scan');
const moveCamera=async(method,id)=>page.evaluate(({method,id})=>{const v=window.__QOIMA_VIEWER__;if(method==='actor')v.selectActor(id);else if(method==='order')v.followOrder();else if(method==='flow')v.flow();else v.overview();},{method,id});
const playTo=async(time,speed,label)=>{
 console.log('CHAPTER '+label);chapters.push({label,simulationTarget:time,speed,videoAt:(Date.now()-storyBegan)/1000});
 await page.evaluate(async({time,speed})=>{
  const v=window.__QOIMA_VIEWER__;v.replay.setSpeed(speed);v.replay.play();
  await new Promise(resolve=>{const check=()=>{const clock=v.replay.getState();if(clock.time>=time||!clock.playing){v.replay.pause();resolve();}else requestAnimationFrame(check);};check();});
 },{time,speed});
};
await page.screenshot({path:resolve(directory,'poster-overview.png')});
await page.waitForTimeout(3000);
await moveCamera('actor','P01');
await playTo(6.4083333333,1,'Pick / real shelf contact');
await page.screenshot({path:resolve(directory,'poster-pick.png')});
await playTo(event('tote_inducted').at_s,1,'Picker and cart / handoff');
await moveCamera('order');
await playTo(event('pack_started').at_s,1,'Conveyor / scripted blocked hold');
await moveCamera('actor','K01');
await playTo(event('order_packed').at_s,10,'Packing / flap mechanism');
await moveCamera('order');
await playTo(100,10,'Parcel outbound / packed is not dispatched');
await moveCamera('actor','F01');
await playTo(Math.min(event('pallet_putaway').at_s,128),10,'Receiving / forklift and seated driver');
await moveCamera('order');
await playTo(scan.start_s,10,'Shipping buffer');
await moveCamera('actor','S01');
await playTo(scan.end_s,1,'Scan / parcel contact');
await moveCamera('order');
await playTo(event('parcel_scanned').at_s,10,'Pallet placement');
await playTo(event('pallet_sealed').at_s,60,'Real fixture clock / 300s pallet age timer');
await moveCamera('actor','F02');
const last=run.actions.filter(action=>action.actor_id==='F02').at(-1);
await playTo(last.end_s,10,'Fork pickup / delivery / return');
await moveCamera('overview');
const elapsed=(Date.now()-storyBegan)/1000;
await page.waitForTimeout(Math.max(0,90-elapsed)*1000);
await page.screenshot({path:resolve(directory,'poster.png')});
const final=await page.evaluate(()=>({clock:window.__QOIMA_VIEWER__.replay.getState(),frame:window.__QOIMA_VIEWER__.replay.getFrame(),audio:window.__QOIMA_VIEWER__.audio.getState()}));
await context.close();const raw=await video.path();await copyFile(raw,resolve(directory,'viewer-recording.webm'));await browser.close();
await writeFile(resolve(directory,'recording.json'),JSON.stringify({source:url,kind:'actual interactive viewer capture; synthetic visual fixture; muted',loadedBuildAssets,readyOffset,wallDuration:(Date.now()-storyBegan)/1000,chapters,final,rawVideo:'viewer-recording.webm'},null,2));
console.log('VIDEO_CAPTURED '+directory);
